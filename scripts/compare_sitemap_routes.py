"""Compare an existing public sitemap with a release candidate."""
import argparse
import json
import sys
from pathlib import Path
from urllib.parse import urlsplit
from xml.etree import ElementTree


SITEMAP_NS = "http://www.sitemaps.org/schemas/sitemap/0.9"


class SitemapError(ValueError):
    pass


def sitemap_urls(path, base_url):
    base = urlsplit(base_url)
    if base.scheme != "https" or not base.netloc or base.query or base.fragment:
        raise SitemapError("base URL must be an HTTPS origin or path without query or fragment")
    prefix = base.path.rstrip("/")

    root = ElementTree.parse(path).getroot()
    if root.tag != f"{{{SITEMAP_NS}}}urlset":
        raise SitemapError("expected a sitemap urlset, not an index or another XML document")
    values = [node.text for node in root.findall(f".//{{{SITEMAP_NS}}}loc")]
    if not values or any(not value for value in values):
        raise SitemapError("sitemap has no complete loc entries")
    if len(values) != len(set(values)):
        raise SitemapError("sitemap contains duplicate loc entries")

    for value in values:
        url = urlsplit(value)
        if url.scheme != base.scheme or url.netloc.lower() != base.netloc.lower():
            raise SitemapError(f"URL is outside the declared origin: {value}")
        if url.query or url.fragment or url.username or url.password:
            raise SitemapError(f"URL is not a canonical page URL: {value}")
        if prefix and url.path != prefix and not url.path.startswith(prefix + "/"):
            raise SitemapError(f"URL is outside the declared project path: {value}")
        if not url.path.startswith("/"):
            raise SitemapError(f"URL has no absolute path: {value}")
    return set(values)


def compare_routes(reference_path, candidate_path, base_url):
    reference = sitemap_urls(reference_path, base_url)
    candidate = sitemap_urls(candidate_path, base_url)
    return {
        "reference_urls": len(reference),
        "candidate_urls": len(candidate),
        "preserved_urls": len(reference & candidate),
        "missing_from_candidate": sorted(reference - candidate),
        "new_in_candidate": sorted(candidate - reference),
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reference", required=True, type=Path, help="saved sitemap from the currently deployed site")
    parser.add_argument("--candidate", required=True, type=Path, help="sitemap generated by the proposed public build")
    parser.add_argument("--base-url", required=True, help="HTTPS site origin and optional project path")
    args = parser.parse_args(argv)
    try:
        result = compare_routes(args.reference, args.candidate, args.base_url)
    except (OSError, SitemapError, ElementTree.ParseError) as error:
        parser.exit(2, f"sitemap comparison failed: {error}\n")
    print(json.dumps(result, indent=2))
    return 1 if result["missing_from_candidate"] else 0


if __name__ == "__main__":
    sys.exit(main())
